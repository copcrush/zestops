#!/usr/bin/env node
/**
 * Generates LOCAL development secrets and writes the .env files every part of
 * ZestOps needs. Works on Windows, macOS and Linux (Node.js only, no packages).
 *
 *   node scripts/setup-local-env.mjs          # create missing files only
 *   node scripts/setup-local-env.mjs --force  # regenerate everything
 *
 * Files written (all git-ignored):
 *   .env                              docker compose (database + backend containers)
 *   apps/web/.env.local               Next.js dev server (port 3000)
 *   services/payment-api/.env         Go API when run outside Docker (go run)
 *   services/monitoring-api/.env      Python API when run outside Docker (uv run)
 *
 * NOTE: --force regenerates database passwords. If the local PostgreSQL volume
 * already exists, recreate it afterwards: docker compose down -v
 */
import { existsSync, writeFileSync } from "node:fs";
import { generateKeyPairSync, randomBytes } from "node:crypto";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const shouldOverwrite = process.argv.includes("--force");

function randomSecret(byteLength = 32) {
  return randomBytes(byteLength).toString("base64url");
}

function toBase64(text) {
  return Buffer.from(text, "utf8").toString("base64");
}

const { publicKey, privateKey } = generateKeyPairSync("ed25519");
const jwtPublicKeyBase64 = toBase64(publicKey.export({ type: "spki", format: "pem" }));
const jwtPrivateKeyBase64 = toBase64(privateKey.export({ type: "pkcs8", format: "pem" }));
const jwtKeyId = `local-${new Date().toISOString().slice(0, 10)}`;

const ownerPassword = randomSecret(24);
const webDatabasePassword = randomSecret(24);
const paymentDatabasePassword = randomSecret(24);
const monitoringDatabasePassword = randomSecret(24);

const postgresPort = "5432";
const databaseName = "zestops";
const testDatabaseName = "zestops_test";

const files = {
  ".env": `# Generated by scripts/setup-local-env.mjs — LOCAL DEVELOPMENT ONLY. Do not commit.
POSTGRES_PORT=${postgresPort}
POSTGRES_DB=${databaseName}
POSTGRES_TEST_DB=${testDatabaseName}
POSTGRES_OWNER_USER=zestops_owner
POSTGRES_OWNER_PASSWORD=${ownerPassword}
ZESTOPS_WEB_DB_PASSWORD=${webDatabasePassword}
ZESTOPS_PAYMENT_DB_PASSWORD=${paymentDatabasePassword}
ZESTOPS_MONITORING_DB_PASSWORD=${monitoringDatabasePassword}

PAYMENT_API_PORT=8080
MONITORING_API_PORT=8000

INTERNAL_JWT_ISSUER=zestops-web
INTERNAL_JWT_PUBLIC_KEY_BASE64=${jwtPublicKeyBase64}
`,

  "apps/web/.env.local": `# Generated by scripts/setup-local-env.mjs — LOCAL DEVELOPMENT ONLY. Do not commit.
APP_ENV=development
APP_ORIGIN=http://localhost:3000
DATABASE_URL=postgres://zestops_web_app:${webDatabasePassword}@localhost:${postgresPort}/${databaseName}
TEST_DATABASE_URL=postgres://zestops_web_app:${webDatabasePassword}@localhost:${postgresPort}/${testDatabaseName}

PAYMENT_API_BASE_URL=http://localhost:8080
MONITORING_API_BASE_URL=http://localhost:8000

CSRF_SECRET=${randomSecret(32)}
INTERNAL_JWT_ISSUER=zestops-web
INTERNAL_JWT_KEY_ID=${jwtKeyId}
INTERNAL_JWT_PRIVATE_KEY_BASE64=${jwtPrivateKeyBase64}

SESSION_IDLE_TIMEOUT_MINUTES=30
SESSION_ABSOLUTE_TIMEOUT_HOURS=8
# Local only: automated logins (E2E tests) all come from 127.0.0.1. Production default is 20.
LOGIN_ATTEMPTS_PER_IP_PER_WINDOW=500
`,

  "services/payment-api/.env": `# Generated by scripts/setup-local-env.mjs — LOCAL DEVELOPMENT ONLY. Do not commit.
APP_ENV=development
PORT=8080
LOG_LEVEL=debug
DATABASE_URL=postgres://zestops_payment_app:${paymentDatabasePassword}@localhost:${postgresPort}/${databaseName}?sslmode=disable
TEST_DATABASE_URL=postgres://zestops_payment_app:${paymentDatabasePassword}@localhost:${postgresPort}/${testDatabaseName}?sslmode=disable
TEST_OWNER_DATABASE_URL=postgres://zestops_owner:${ownerPassword}@localhost:${postgresPort}/${testDatabaseName}?sslmode=disable
INTERNAL_JWT_ISSUER=zestops-web
INTERNAL_JWT_AUDIENCE=zestops-payment-api
INTERNAL_JWT_PUBLIC_KEY_BASE64=${jwtPublicKeyBase64}
RATE_LIMIT_REQUESTS_PER_MINUTE=120
`,

  "services/monitoring-api/.env": `# Generated by scripts/setup-local-env.mjs — LOCAL DEVELOPMENT ONLY. Do not commit.
APP_ENV=development
PORT=8000
LOG_LEVEL=DEBUG
DATABASE_URL=postgresql+asyncpg://zestops_monitoring_app:${monitoringDatabasePassword}@localhost:${postgresPort}/${databaseName}
TEST_DATABASE_URL=postgresql+asyncpg://zestops_monitoring_app:${monitoringDatabasePassword}@localhost:${postgresPort}/${testDatabaseName}
TEST_OWNER_DATABASE_URL=postgresql+asyncpg://zestops_owner:${ownerPassword}@localhost:${postgresPort}/${testDatabaseName}
INTERNAL_JWT_ISSUER=zestops-web
INTERNAL_JWT_AUDIENCE=zestops-monitoring-api
INTERNAL_JWT_PUBLIC_KEY_BASE64=${jwtPublicKeyBase64}
MONITORING_ALLOWED_TARGETS=http://localhost:8080,http://localhost:8000,http://payment-api:8080,http://monitoring-api:8000
MONITORING_ALLOW_PRIVATE_NETWORK_TARGETS=true
DEMO_ENDPOINTS_ENABLED=true
RATE_LIMIT_REQUESTS_PER_MINUTE=120
`,
};

// The files share secrets (the JWT key pair, database passwords), so they are
// generated together or not at all. Mixing old and new files would break login.
const existingFiles = Object.keys(files).filter((relativePath) =>
  existsSync(join(repositoryRoot, relativePath)),
);

if (existingFiles.length === Object.keys(files).length && !shouldOverwrite) {
  console.log("All local .env files already exist. Nothing to do (use --force to regenerate).");
  process.exit(0);
}

if (existingFiles.length > 0 && !shouldOverwrite) {
  console.error(
    `Some .env files already exist (${existingFiles.join(", ")}) but others are missing.\n` +
      "They must share the same secrets. Re-run with --force to regenerate all of them,\n" +
      "then recreate the database volume: docker compose down -v",
  );
  process.exit(1);
}

for (const [relativePath, content] of Object.entries(files)) {
  writeFileSync(join(repositoryRoot, relativePath), content, { encoding: "utf8", mode: 0o600 });
  console.log(`created ${relativePath}`);
}

if (shouldOverwrite && existingFiles.length > 0) {
  console.log("\nSecrets regenerated. Recreate the local database volume: docker compose down -v");
}
console.log("\nDone. These files contain local-only secrets and are ignored by git.");
